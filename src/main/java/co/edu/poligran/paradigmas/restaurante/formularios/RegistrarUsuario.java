    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

    // Capturar datos de los componentes visuales
    String nombre = txtNombre.getText().trim();
    String apellido = txtApellido.getText().trim();
    int tipoDoc = cbxTipoDoc.getSelectedIndex(); 
    String textoNumDoc = txtNumDoc.getText().trim();
    String textoEdad = txtEdad.getText().trim();
    String correo = txtCorreo.getText().trim();
    String celularStr = txtCelular.getText().trim();
    String nombreUsuario = txtNombreUsuario.getText().trim();
    
    String password = new String(txtContraseña.getPassword());
    String confirmarPassword = new String(txtConfirmaContraseña.getPassword());
    String rol = cbxRol.getSelectedItem() != null ? cbxRol.getSelectedItem().toString() : "Cliente";

    // Validaciones de contenido vacío
    if (!Validaciones.tieneContenido(nombre) || !Validaciones.tieneContenido(apellido) ||
        !Validaciones.tieneContenido(textoNumDoc) || !Validaciones.tieneContenido(textoEdad) ||
        !Validaciones.tieneContenido(correo) || !Validaciones.tieneContenido(celularStr) ||
        !Validaciones.tieneContenido(nombreUsuario) || !Validaciones.tieneContenido(password)) {
        
        JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Validaciones de formato
    if (!Validaciones.esCorreo(correo)) {
        JOptionPane.showMessageDialog(this, "El formato del correo electrónico no es válido.", "Error de formato", JOptionPane.WARNING_MESSAGE);
        txtCorreo.requestFocusInWindow();
        return;
    }

    if (!Validaciones.esTelefono(celularStr)) {
        JOptionPane.showMessageDialog(this, "El número de teléfono o celular no es válido.", "Error de formato", JOptionPane.WARNING_MESSAGE);
        txtCelular.requestFocusInWindow();
        return;
    }

    if (!password.equals(confirmarPassword)) {
        JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden.", "Error de contraseña", JOptionPane.WARNING_MESSAGE);
        txtContraseña.requestFocusInWindow();
        return;
    }

    try {
        int numDoc = Integer.parseInt(textoNumDoc);
        int edad = Integer.parseInt(textoEdad);
        long celular = Long.parseLong(celularStr);

        // Construir objeto Persona2
        Persona2 nuevoUsuario = new Persona2();
        nuevoUsuario.setNombre(nombre);
        nuevoUsuario.setApellido(apellido);
        nuevoUsuario.setTipoDoc(tipoDoc);
        nuevoUsuario.setNumDoc(numDoc);
        nuevoUsuario.setCorreo(correo);
        nuevoUsuario.setContraseña(password);
        nuevoUsuario.setCelular(celular);
        nuevoUsuario.setNombreUsuario(nombreUsuario);
        nuevoUsuario.setRol(rol);

        // Registrar usando la instancia global estática
        Persona2 resultado = RestauranteFormulario.anaManager.registrarPersona(nuevoUsuario);

        if (resultado != null) {
            JOptionPane.showMessageDialog(this, "¡Usuario registrado exitosamente!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            this.dispose(); // Cierra el registro y vuelve al login
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar. Es posible que el documento, correo, celular o usuario ya existan.", "Error de Duplicidad", JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Documento, edad y celular deben ser numéricos.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

